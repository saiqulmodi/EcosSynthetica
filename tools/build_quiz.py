"""Copy matching questions from the School MCQ Bank into js/quizbank.js.

Each of the game's four forms gets questions from the bank topics that fit it.
Run again after the bank is rebuilt:  python tools/build_quiz.py
"""
import json
import random
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANK = Path(r"C:\Users\saiqu\Projects\School_MCQ_Bank\output\mcq_bank.db")
OUT = ROOT / "js" / "quizbank.js"
PER_FORM = 70

TOPICS = {
    0: ["Microorganisms: friend and foe", "Microbes in human welfare", "Cell: structure and functions",
        "Biotechnology: principles and applications", "Life processes"],
    1: ["Photosynthesis and respiration in plants", "Our environment: food chains and energy flow", "Nutrition in plants",
        "Crop production and management", "Improvement in food resources", "Forests: our lifeline", "Roots of plants",
        "Plants: needs and parts", "Seeds and germination"],
    2: ["Honeybees", "Insects and small creatures", "Flowers and pollination", "Organisms and populations",
        "Our environment: food chains and energy flow", "Food habits of animals", "Super senses of animals"],
    3: ["Why do we fall ill (diseases)", "Human health and disease", "Good habits, health and hygiene",
        "Microbes in human welfare", "Evolution", "Famous Indians in science and environment", "Human physiology"],
}


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    con = sqlite3.connect(BANK)
    rng = random.Random(7)
    data = {}
    for form, topics in TOPICS.items():
        rows = con.execute(
            f"select id, class_level, topic, question, option_a, option_b, option_c, option_d, correct_option, explanation "
            f"from questions where topic in ({','.join('?' * len(topics))})", topics).fetchall()
        seen = set()
        picked = []
        rng.shuffle(rows)
        for r in rows:
            q = r[3].strip()
            if q in seen:
                continue
            seen.add(q)
            picked.append({"id": r[0], "cls": r[1], "topic": r[2], "q": q, "opts": list(r[4:8]),
                           "ans": "ABCD".index(r[8]), "why": r[9] or ""})
            if len(picked) >= PER_FORM:
                break
        data[form] = picked
        print(f"form {form}: {len(picked)} questions")
    OUT.write_text("// Generated by tools/build_quiz.py from the School MCQ Bank. Do not edit by hand.\n"
                   "export const BANK = " + json.dumps(data, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
