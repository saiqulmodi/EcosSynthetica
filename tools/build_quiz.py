"""Copy matching questions from the NEET Data Hub into js/quizbank.js.

Each of the game's four forms gets questions from the hub chapters that fit it: NEET (NCERT Class 11-12)
chapters plus the foundation topics of the School MCQ Bank that the hub includes.
Run again after the hub is rebuilt:  python tools/build_quiz.py
"""
import json
import random
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HUB = Path(r"C:\Users\saiqu\Projects\NEET_Data_Hub\output\neet_hub.db")
OUT = ROOT / "js" / "quizbank.js"
PER_FORM = 80

# NEET chapter ids, and foundation chapter titles, for each form.
FORMS = {
    0: (["b11-02", "b11-08", "b12-08", "b12-09"],
        ["Microorganisms: friend and foe", "Microbes in human welfare", "Cell: structure and functions"]),
    1: (["b11-03", "b11-05", "b11-11", "b11-13", "b12-01", "b12-11", "b12-12"],
        ["Photosynthesis and respiration in plants", "Nutrition in plants", "Crop production and management", "Seeds and germination"]),
    2: (["b11-04", "b11-07", "b12-11", "b12-12", "b12-13"],
        ["Honeybees", "Insects and small creatures", "Flowers and pollination", "Food habits of animals"]),
    3: (["b12-07", "b11-14", "b11-15", "b11-16", "b11-19", "b12-06"],
        ["Why do we fall ill (diseases)", "Good habits, health and hygiene", "Famous Indians in science and environment"]),
}


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    con = sqlite3.connect(HUB)
    rng = random.Random(7)
    data = {}
    for form, (neet_ids, found_titles) in FORMS.items():
        rows = con.execute(
            f"select q.id, q.class_level, c.title, q.question, q.option_a, q.option_b, q.option_c, q.option_d, q.correct_option, q.explanation "
            f"from questions q join chapters c on c.id = q.chapter_id "
            f"where q.chapter_id in ({','.join('?' * len(neet_ids))}) or (q.class_level <= 10 and c.title in ({','.join('?' * len(found_titles))}))",
            [*neet_ids, *found_titles]).fetchall()
        # Spread the picks across chapters so no single chapter dominates.
        by_ch = {}
        for r in rows:
            by_ch.setdefault(r[2], []).append(r)
        lists = [rng.sample(v, len(v)) for v in by_ch.values()]
        rng.shuffle(lists)
        picked = []
        while len(picked) < PER_FORM and any(lists):
            for lst in lists:
                if lst and len(picked) < PER_FORM:
                    r = lst.pop()
                    picked.append({"id": r[0], "cls": r[1], "topic": r[2], "q": r[3], "opts": list(r[4:8]),
                                   "ans": "ABCD".index(r[8]), "why": r[9] or ""})
        data[form] = picked
        print(f"form {form}: {len(picked)} questions from {len(by_ch)} chapters")
    OUT.write_text("// Generated by tools/build_quiz.py from the NEET Data Hub. Do not edit by hand.\n"
                   "export const BANK = " + json.dumps(data, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
